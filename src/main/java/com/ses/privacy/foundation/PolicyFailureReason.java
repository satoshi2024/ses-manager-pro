package com.ses.privacy.foundation;

/**
 * ポリシー評価における型付けされた失敗原因。
 * 例外メッセージ文字列の照合に依存せず、型安全な分岐を提供する。
 */
public enum PolicyFailureReason {
    NONE,

    // ACCESS_DENIED (呼び出し元の拒絶)
    MISSING_CALLER_IDENTITY,
    CALLER_TENANT_MISMATCH,
    CALLER_ACTOR_MISMATCH,
    UNAUTHORIZED_ACTOR_ROLE,

    // POLICY_UNKNOWN (未決・不明・障害)
    POLICY_NOT_FOUND,
    POLICY_UNAPPROVED,
    REVOCATION_STATUS_UNKNOWN,
    REVOCATION_PROVIDER_ERROR,
    STORE_UNAVAILABLE,

    // POLICY_EXPIRED (時刻・期限不適合)
    NOT_YET_ISSUED,
    NOT_YET_EFFECTIVE,
    EXPIRED_AT_OR_AFTER_DEADLINE,
    AUTHORITY_VALIDITY_EXPIRED,

    // POLICY_REVOKED (明示的失効)
    KEY_REVOKED,
    ENVELOPE_REVOKED,

    // POLICY_DRIFT (ポリシー自体の改竄・不整合・照合失敗)
    UNSUPPORTED_SCHEMA_VERSION,
    UNKNOWN_TRUST_ANCHOR,
    AUTHORITY_SCOPE_MISMATCH,
    POLICY_ID_MISMATCH,
    REVISION_MISMATCH,
    DIGEST_MISMATCH,
    SIGNATURE_INVALID,
    SOD_VIOLATION,
    TENANT_MISMATCH,
    SCOPE_MISMATCH,
    DATA_ELEMENT_MISMATCH,
    ACTION_MISMATCH,
    PROVIDER_MISMATCH
}
